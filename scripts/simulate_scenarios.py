#!/usr/bin/env python3
"""simulate_scenarios.py — fault-scenario simulator and matrix builder.

Usage: simulate_scenarios.py
  writes outputs/scenario-<name>.log (synthetic log, SIMULATED),
         outputs/scenario-<name>-ledger-state.json,
         outputs/scenario-<name>.log is parsed with validation_lib and all
         five detectors are run on each scenario,
         outputs/matrix.md, outputs/matrix.csv,
         outputs/scenario-summary.json.

SIMULATED-DATA DISCLOSURE: every number in the matrix comes from this
script's documented model parameters below — not from a live network.
The model is: one expected validation per ledger, nominal close interval
4 s, 600 ledgers per scenario (40-minute window). A fault removes a
fixed number of validation slots; recovery time is the modelled time
from fault end to the first accepted validation. The detectors are run
on the simulated timelines with the same code as on the fixtures, so
the matrix's "detectors fired" column is OBSERVED detector behaviour
on SIMULATED timelines.

Two views are kept apart and labelled:
  - local-issuance view: what the node's own log shows (CNF Val lines).
  - network-acceptance view: validations the network would count. In
    the clock-jump scenario the node still issues validations locally,
    but their signTime is outside the pinned acceptance window, so the
    network rejects them; the matrix counts them as missed.
"""

import hashlib
import json
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import validation_lib as vl  # noqa: E402

BASE_TIME = datetime(2026, 11, 20, 0, 0, 0, tzinfo=timezone.utc)
CLOSE_INTERVAL_S = 4
FIRST_SEQ = 910000
SLOTS = 600
COOKIE = 987654321
NODE_KEY = "n9SyntheticValidatorIdentity0000000000000000000"
NODE_ACCOUNT = "rSyntheticValidatorAccount0000000000000"
PEERS = ["203.0.113.%d:2559" % i for i in range(1, 13)]

# --- documented model parameters (change them here, nowhere else) ---
PARAMS = {
    "network-partition": {
        "partition_start_slot": 200, "partition_seconds": 300,
        "resume_lag_slots": 2,
        "cause": "all 12 peers disconnect at once; no proposals reach the "
                 "node, so no ledger closes locally and no validation is "
                 "issued for 75 slots"},
    "process-restart": {
        "down_start_slot": 200, "down_seconds": 180,
        "restart_lag_slots": 3,
        "cause": "process down for 180 s (45 slots); engine restarts and "
                 "re-validates 3 slots after the restart line"},
    "clock-jump": {
        "skew_start_slot": 150, "skew_seconds": 400,
        "skew_duration_seconds": 240,
        "resync_lag_slots": 1,
        "cause": "local clock jumps +400 s for 240 s (60 slots); "
                 "validations are issued locally but their signTime is "
                 "outside the pinned acceptance window, so the network "
                 "rejects them"},
    "disk-pressure": {
        "fatal_slot": 300, "grace_seconds": 60, "halt_seconds": 240,
        "recovery_lag_slots": 4,
        "cause": "fatal low-disk line at slot 300; the node keeps "
                 "validating for a 60 s grace period, then halts for "
                 "240 s (60 slots) until disk space is freed"},
}


def fmt(ts):
    return ts.strftime("%Y-%m-%dT%H:%M:%S.") + "%03dZ" % (ts.microsecond // 1000)


def close_time(slot):
    return BASE_TIME + timedelta(seconds=CLOSE_INTERVAL_S * slot)


def ledger_hash(seq):
    return hashlib.sha256(("postfiatd-ledger-%d" % seq).encode()).hexdigest()


def scenario_timeline(name):
    """Return (log_lines, ledger_state, model) for one scenario."""
    p = PARAMS.get(name, {})
    lines = [
        "# SIMULATED SCENARIO — generated by scripts/simulate_scenarios.py, "
        "not a real node log.",
        "# scenario: %s" % name,
        "# pinned postfiatd commit: %s" % vl.PINNED_COMMIT,
        "# model: %d slots x %d s close interval, first seq %d"
        % (SLOTS, CLOSE_INTERVAL_S, FIRST_SEQ),
    ]
    ledgers = []
    # per-slot: validated locally? sign offset? extra log lines?
    validated = [True] * SLOTS
    sign_off = [0] * SLOTS
    extra = {}  # slot -> [extra log lines]
    if name == "baseline":
        pass
    elif name == "network-partition":
        start = p["partition_start_slot"]
        n = p["partition_seconds"] // CLOSE_INTERVAL_S
        for i in range(start, start + n):
            validated[i] = False
        ct = close_time(start)
        for peer in PEERS:
            extra.setdefault(start, []).append(
                "%s [Peer] %s failed: Connection reset by peer"
                % (fmt(ct), peer))
            extra.setdefault(start, []).append(
                "%s [Peer] Closed" % fmt(ct))
        extra.setdefault(start, []).append(
            "%s [RCLConsensus] Need consensus ledger %s"
            % (fmt(ct), ledger_hash(FIRST_SEQ + start)))
    elif name == "process-restart":
        start = p["down_start_slot"]
        n = p["down_seconds"] // CLOSE_INTERVAL_S
        for i in range(start, start + n):
            validated[i] = False
        restart_slot = start + n
        ct = close_time(restart_slot)
        extra.setdefault(restart_slot, []).append(
            "%s [RCLConsensus] Consensus engine started (cookie: %d)"
            % (fmt(ct), COOKIE))
        extra.setdefault(restart_slot, []).append(
            "%s [RCLConsensus] Validator identity: %s" % (fmt(ct), NODE_KEY))
    elif name == "clock-jump":
        start = p["skew_start_slot"]
        n = p["skew_duration_seconds"] // CLOSE_INTERVAL_S
        for i in range(start, start + n):
            sign_off[i] = p["skew_seconds"]
    elif name == "disk-pressure":
        fatal = p["fatal_slot"]
        grace = p["grace_seconds"] // CLOSE_INTERVAL_S
        halt = p["halt_seconds"] // CLOSE_INTERVAL_S
        for i in range(fatal + grace, fatal + grace + halt):
            validated[i] = False
        extra.setdefault(fatal, []).append(
            "%s [Node] Remaining free disk space is less than 512MB"
            % fmt(close_time(fatal)))
    # engine start + identity at window start (except restart scenario,
    # which also gets them at its restart slot)
    lines.append(
        "%s [RCLConsensus] Consensus engine started (cookie: %d)"
        % (fmt(BASE_TIME - timedelta(seconds=5)), COOKIE))
    lines.append(
        "%s [RCLConsensus] Validator identity: %s"
        % (fmt(BASE_TIME - timedelta(seconds=5)), NODE_KEY))
    for slot in range(SLOTS):
        seq = FIRST_SEQ + slot
        ct = close_time(slot)
        for line in extra.get(slot, []):
            lines.append(line)
        h = ledger_hash(seq)
        lines.append("%s [RCLConsensus] CNF buildLCL %s" % (fmt(ct), h))
        if validated[slot]:
            lines.append("%s [RCLConsensus] CNF Val %s" % (fmt(ct), h))
            lines.append(
                "%s [Validations] RCLValidations: Recording vote with "
                "signing key: %s -> Account: %s"
                % (fmt(ct), NODE_KEY, NODE_ACCOUNT))
        st = ct + timedelta(seconds=sign_off[slot])
        ledgers.append({
            "seq": seq, "hash": h,
            "close_time": fmt(ct), "sign_time": fmt(st),
            "validated": validated[slot],
        })
    state = {
        "scenario": name,
        "synthetic": True,
        "simulated": True,
        "generated_by": "scripts/simulate_scenarios.py",
        "pinned_commit": vl.PINNED_COMMIT,
        "base_close_time": fmt(BASE_TIME),
        "close_interval_s": CLOSE_INTERVAL_S,
        "first_seq": FIRST_SEQ,
        "model_parameters": p,
        "ledgers": ledgers,
    }
    return lines, state


def recovery_seconds(name, events):
    """Modelled recovery time: fault end -> first accepted validation."""
    if name == "baseline":
        return None
    p = PARAMS[name]
    if name == "network-partition":
        end_slot = p["partition_start_slot"] + p["partition_seconds"] // CLOSE_INTERVAL_S
        return p["resume_lag_slots"] * CLOSE_INTERVAL_S
    if name == "process-restart":
        return p["restart_lag_slots"] * CLOSE_INTERVAL_S
    if name == "clock-jump":
        return p["resync_lag_slots"] * CLOSE_INTERVAL_S
    if name == "disk-pressure":
        return p["recovery_lag_slots"] * CLOSE_INTERVAL_S
    return None


def main(argv):
    root = Path(__file__).resolve().parent.parent
    out_dir = root / "outputs"
    out_dir.mkdir(parents=True, exist_ok=True)
    scenarios = ["baseline", "network-partition", "process-restart",
                 "clock-jump", "disk-pressure"]
    rows = []
    summary = {"scenarios": {}}
    for name in scenarios:
        lines, state = scenario_timeline(name)
        log_path = out_dir / ("scenario-%s.log" % name)
        json_path = out_dir / ("scenario-%s-ledger-state.json" % name)
        log_text = "\n".join(lines) + "\n"
        log_path.write_text(log_text, encoding="utf-8")
        json_text = json.dumps(state, indent=2) + "\n"
        json_path.write_text(json_text, encoding="utf-8")
        log_sha = hashlib.sha256(log_text.encode()).hexdigest()
        events = vl.parse_log(log_path, state)
        events["_ledger_state"] = state
        # Network-acceptance view: a locally issued validation counts only
        # if its signTime is inside the pinned acceptance window.
        accepted = 0
        for l in state["ledgers"]:
            if not l["validated"]:
                continue
            off = vl.parse_iso(l["sign_time"]) - vl.parse_iso(l["close_time"])
            if -vl.VALIDATION_CURRENT_EARLY_S <= off <= vl.VALIDATION_CURRENT_WALL_S:
                accepted += 1
        expected = len(state["ledgers"])
        issued = events["summary"]["validated_ledgers"]
        missed = expected - accepted
        downtime = missed * CLOSE_INTERVAL_S
        fired = {}
        for dname, fn in vl.DETECTORS.items():
            ev = fn(events)
            if not ev["verdict"].startswith("NO_"):
                fired[dname] = ev["verdict"]
        row = {
            "scenario": name,
            "expected": expected,
            "issued_locally": issued,
            "accepted_by_network": accepted,
            "missed": missed,
            "missed_pct": round(100.0 * missed / expected, 2),
            "uptime_pct": round(100.0 * accepted / expected, 2),
            "downtime_s": downtime,
            "recovery_s": recovery_seconds(name, events),
            "detectors_fired": fired,
            "primary_cause": (PARAMS[name]["cause"] if name in PARAMS
                              else "none — healthy control"),
            "scenario_log_sha256": log_sha,
        }
        rows.append(row)
        summary["scenarios"][name] = row
        rec = "n/a" if row["recovery_s"] is None else "%ds" % row["recovery_s"]
        print("scenario %s: expected=%d issued=%d accepted=%d missed=%d "
              "uptime=%.2f%% downtime=%ds recovery=%s detectors=%s"
              % (name, expected, issued, accepted, missed,
                 row["uptime_pct"], downtime, rec, fired or "none"))
    # matrix.csv
    cols = ["scenario", "expected", "issued_locally", "accepted_by_network",
            "missed", "missed_pct", "uptime_pct", "downtime_s", "recovery_s",
            "detectors_fired", "primary_cause"]
    csv_lines = [",".join(cols)]
    for r in rows:
        csv_lines.append(",".join([
            r["scenario"], str(r["expected"]), str(r["issued_locally"]),
            str(r["accepted_by_network"]), str(r["missed"]),
            "%.2f" % r["missed_pct"], "%.2f" % r["uptime_pct"],
            str(r["downtime_s"]),
            "" if r["recovery_s"] is None else str(r["recovery_s"]),
            ";".join("%s=%s" % kv for kv in sorted(r["detectors_fired"].items())) or "none",
            '"%s"' % r["primary_cause"],
        ]))
    (out_dir / "matrix.csv").write_text("\n".join(csv_lines) + "\n", encoding="utf-8")
    # matrix.md
    md = ["# Reproducibility matrix — SIMULATED fault scenarios",
          "",
          "All numbers below are SIMULATED: they come from the documented "
          "model in `scripts/simulate_scenarios.py` (600 slots x 4 s close "
          "interval, first seq 910000, base 2026-11-20T00:00:00Z). "
          "Detectors were run on the simulated timelines with the same code "
          "as on the fixtures, so the 'detectors fired' column is OBSERVED "
          "detector behaviour on SIMULATED timelines.",
          "",
          "| scenario | expected | issued locally | accepted by network | "
          "missed | missed % | uptime % | downtime (s) | recovery (s) | "
          "detectors fired |",
          "|---|---:|---:|---:|---:|---:|---:|---:|---:|---|",
          ]
    for r in rows:
        md.append("| %s | %d | %d | %d | %d | %.2f | %.2f | %d | %s | %s |"
                  % (r["scenario"], r["expected"], r["issued_locally"],
                     r["accepted_by_network"], r["missed"], r["missed_pct"],
                     r["uptime_pct"], r["downtime_s"],
                     "" if r["recovery_s"] is None else str(r["recovery_s"]),
                     "; ".join("%s=%s" % kv for kv in sorted(r["detectors_fired"].items())) or "none"))
    md += ["",
           "Definitions: *missed* = expected − accepted by network; "
           "*uptime %* = accepted / expected; *downtime* = missed × 4 s; "
           "*recovery* = modelled time from fault end to the first "
           "accepted validation (see simulate_scenarios.py model "
           "parameters). In the clock-jump scenario the node issues "
           "validations locally but the network rejects them as stale, so "
           "issued locally (600) exceeds accepted (540).",
           "",
           "Primary causes (modelled):",
           ""]
    for r in rows:
        md.append("- **%s**: %s" % (r["scenario"], r["primary_cause"]))
    md.append("")
    (out_dir / "matrix.md").write_text("\n".join(md), encoding="utf-8")
    (out_dir / "scenario-summary.json").write_text(
        json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
